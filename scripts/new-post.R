# From the website root: Rscript scripts/new-post.R my-post "My *title*"
args <- commandArgs(trailingOnly = TRUE)
if (length(args) < 1L) stop("Usage: Rscript scripts/new-post.R slug [title]")
slug <- args[1]
if (!grepl("^[a-z0-9]+(-[a-z0-9]+)*$", slug)) stop("Use a lowercase hyphen-separated slug.")
if (!file.exists("_quarto.yml")) stop("Run from the website project root.")
destination <- file.path("posts", slug)
if (dir.exists(destination)) stop("That post folder already exists; nothing was overwritten.")
title <- if (length(args) >= 2L) args[2] else gsub("-", " ", slug)
lines <- readLines("_templates/post.qmd", warn = FALSE, encoding = "UTF-8")
lines[grepl("^title:",lines)] <- paste0("title: ",encodeString(title, quote = '"'))
lines[grepl("^date:",lines)] <- paste0("date: ",format(Sys.Date(),"%Y-%m-%d"))
lines <- gsub("posts/your-post/results.csv",paste0(destination,"/results.csv"),lines,fixed=TRUE)
dir.create(destination, recursive = TRUE)
writeLines(enc2utf8(lines),file.path(destination,"index.qmd"),useBytes=TRUE)
cat("Created",file.path(destination,"index.qmd"),"\n")
